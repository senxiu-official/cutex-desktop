import { createServer, type ServerResponse } from "node:http";
import { expect, it, vi } from "vitest";
vi.mock("electron", () => ({ BrowserWindow: { getFocusedWindow: () => null, getAllWindows: () => [] }, dialog: {}, shell: {} }));
import { DaemonService } from "../src/main/daemon";

it("real HTTP/SSE → CutexClient EventFeed → daemon hostEvent carries null and generation without list refetch", async () => {
  let sse: ServerResponse | undefined, activeRead: ServerResponse | undefined;
  const requests: URL[] = [];
  let activeCalls = 0;
  const server = createServer((req, res) => {
    const url = new URL(req.url!, "http://127.0.0.1"); requests.push(url);
    const json = (value: unknown) => { res.setHeader("Content-Type", "application/json"); res.end(JSON.stringify(value)); };
    if (url.pathname === "/v2/host") return json({ hostId: "test-host" });
    if (url.pathname === "/v2/events/stream") {
      sse = res; res.writeHead(200, { "Content-Type": "text/event-stream" }); res.write(": connected\n\n"); return;
    }
    if (url.pathname === "/v2/events") return json({ streamId: "stream", events: [], nextCursor: "c0", hasMore: false });
    if (url.pathname === "/v2/sessions") {
      if (url.searchParams.get("lifecycle") === "retired") return json({ sessions: [] });
      if (++activeCalls === 1) return json({ sessions: [], management: { eventStream: { streamId: "stream", latest: { cursor: "c0" } } } });
      activeRead = res; return;
    }
    if (url.pathname === "/v2/projects") return json({ projects: [] });
    if (url.pathname === "/v2/host/sessions") return json({ data: [], nextCursor: null });
    res.writeHead(404); res.end();
  });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const emit = vi.fn();
  const service = new DaemonService(emit);
  try {
    const port = (server.address() as { port: number }).port;
    service.useEndpoint({ baseUrl: `http://127.0.0.1:${port}`, token: "private-test" }, { remote: true });
    await vi.waitFor(() => expect(sse).toBeDefined());
    const streamUrl = requests.find(url => url.pathname === "/v2/events/stream")!;
    expect(streamUrl.searchParams.get("sessionStatus")).toBe("true");
    expect(streamUrl.searchParams.has("liveDeltas")).toBe(false);
    const read = service.sidebar();
    await vi.waitFor(() => expect(activeRead).toBeDefined());
    // Exact envelope generated by backend write_session_status, no SSE id.
    for (const backgroundWork of [{ running: true, terminals: 1 }, null]) {
      const envelope = { contractVersion: 2, eventId: "live-test", cursor: "", streamId: "stream", sequence: 0,
        receivedAt: "2026-11-04T00:00:00Z", cutexSessionId: "agent", hostId: "test-host", source: "cutex", sensitivity: "owner", correlation: {},
        cutex: { method: "cutex/session/backgroundWork/changed", params: { cutexSessionId: "agent", runtimeGeneration: 2, backgroundWork } } };
      sse!.write(`event: session_status\ndata: ${JSON.stringify(envelope)}\n\n`);
    }
    await vi.waitFor(() => expect(emit.mock.calls.filter(([name]) => name === "hostEvent")).toHaveLength(2));
    const events = emit.mock.calls.filter(([name]) => name === "hostEvent").map(([, envelope]) => envelope);
    expect(events[0].correlation.runtimeGeneration).toBe(2);
    expect(events[1].cutex.params.backgroundWork).toBeNull();
    activeRead!.setHeader("Content-Type", "application/json");
    activeRead!.end(JSON.stringify({ sessions: [{ cutexSessionId: "agent", runtime: { runtimeGeneration: 2, backgroundWork: { running: true } } }] }));
    expect((await read).active[0]!.runtime.backgroundWork).toBeNull();
    expect(activeCalls).toBe(2); // initial tail + explicit sidebar only, no dirty follow-up
  } finally {
    service.stop();
    server.closeAllConnections();
    await new Promise<void>(resolve => server.close(() => resolve()));
  }
});
