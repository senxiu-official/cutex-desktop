#!/usr/bin/env node
// Generates what the app and the builder need to know about this package's entries, from their source:
//   exports.json                                                   each entry's value names and the shared libraries, for the builder
//   apps/desktop/src/renderer/src/moduleApi/hostTable.generated.ts the app's host table, with its compile-time check
// test/generated.test.ts fails when either is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const ROOT = new URL("../", import.meta.url);
const TABLE = new URL("../../apps/desktop/src/renderer/src/moduleApi/hostTable.generated.ts", ROOT);
const ENTRIES = [
  { spec: "@cutex-desktop/module-api", file: "src/index.ts", impl: "stable" },
  { spec: "@cutex-desktop/module-api/ui", file: "src/ui.ts", impl: "ui" },
  { spec: "@cutex-desktop/module-api/experimental", file: "src/experimental.ts", impl: "experimental" },
];
/** Libraries a module shares with the app: a second copy of React would break hooks. */
const SHARED = ["react", "react/jsx-runtime", "react-dom"];

/** The names an entry declares. Each is a top-level `export declare function|const NAME`; the type check catches anything else. */
function valueNames(file) {
  const text = readFileSync(new URL(file, ROOT), "utf8");
  if (/^export (?!declare |type |interface )/m.test(text)) throw new Error(`${file}: an entry exports only declarations and types; the code lives in the app`);
  return [...new Set([...text.matchAll(/^export declare (?:function|const) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]))].sort();
}

export function generated() {
  const version = JSON.parse(readFileSync(new URL("package.json", ROOT), "utf8")).version;
  const entries = ENTRIES.map((e) => ({ ...e, names: valueNames(e.file) }));
  const exportsJson = `${JSON.stringify({ moduleApi: version.split(".").slice(0, 2).join("."), shared: SHARED, entries: Object.fromEntries(entries.map((e) => [e.spec, e.names])) }, null, 2)}\n`;
  const table = [
    "// Generated by packages/module-api/scripts/generate-host.mjs from that package's entries. Do not edit.",
    "// `satisfies typeof …` makes a missing name, an extra one or a wrong type a compile error.",
    ...entries.map((e) => `import type * as ${e.impl}Api from "${e.spec}";`),
    ...entries.map((e) => `import * as ${e.impl} from "./${e.impl}";`),
    "",
    "export const MODULE_API_HOST: Readonly<Record<string, Readonly<Record<string, unknown>>>> = Object.freeze({",
    ...entries.flatMap((e) => [`  ${JSON.stringify(e.spec)}: Object.freeze({`, ...e.names.map((n) => `    ${n}: ${e.impl}.${n},`), `  } satisfies typeof ${e.impl}Api),`]),
    "});",
    "",
  ].join("\n");
  return { exportsJson, table };
}

export const generatedPaths = { exportsJson: new URL("exports.json", ROOT), table: TABLE };

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const { exportsJson, table } = generated();
  writeFileSync(generatedPaths.exportsJson, exportsJson);
  writeFileSync(generatedPaths.table, table);
}
