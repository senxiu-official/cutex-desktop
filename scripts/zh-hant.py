#!/usr/bin/env python3
"""A module's zh-Hant-CN block from its zh-CN one, by OpenCC s2t (character level, terms unchanged: 軟件 stays 軟件;
the same conversion i18n/zh-Hant-CN.ts was generated with).

    python3 scripts/zh-hant.py apps/desktop/src/renderer/src/modules/<id>/i18n.ts           # print the block
    python3 scripts/zh-hant.py --write apps/desktop/src/renderer/src/modules/<id>/i18n.ts   # put it in the file

Reads the `export const zhCN = { … };` block (one `"key": "value",` entry per line). Without `--write` it prints
`const zhHantCN … = { … };`. With `--write` it replaces that block in the file, or, the first time, appends it with the
`ModuleZhHantMessages` declaration and `export const locales = { "zh-Hant-CN": zhHantCN }` (as modules/perf-log does).
Run it again after changing a Chinese string, then read the diff: s2t is character-level, so a word Taiwan / Hong Kong
write differently stays mainland usage on purpose (zh-Hant-CN = traditional characters, mainland terms).

OpenCC is a Python package. When it is not installed the script re-runs itself through `uvx --with opencc` (uv: found
on PATH or at ~/.local/bin/uvx), so plain `python3` works on any machine with uv.
docs/widget-authoring-guide.md §2 Step 2."""
import json
import os
import re
import shutil
import sys

HEADER = "// zh-Hant-CN: generated by scripts/zh-hant.py (OpenCC s2t, mainland terms kept); regenerate, do not hand-edit."


def find_uvx():
    found = shutil.which("uvx")
    if found:
        return found
    for path in ("~/.local/bin/uvx", "~/.cargo/bin/uvx"):
        full = os.path.expanduser(path)
        if os.access(full, os.X_OK):
            return full
    return None


try:
    import opencc
except ImportError:
    if os.environ.get("ZH_HANT_REEXEC"):
        sys.exit("zh-hant: OpenCC still missing after `uvx --with opencc`; check uv's network access")
    uvx = find_uvx()
    if not uvx:
        sys.exit(
            "zh-hant: needs the OpenCC Python package and none is installed.\n"
            "  Either install uv (https://docs.astral.sh/uv/; then this script finds `uvx` itself),\n"
            "  or `pip install --user opencc` and run it again."
        )
    os.environ["ZH_HANT_REEXEC"] = "1"
    os.execv(uvx, [uvx, "--quiet", "--with", "opencc", "python3", os.path.abspath(__file__), *sys.argv[1:]])

args = sys.argv[1:]
write = "--write" in args
paths = [a for a in args if a != "--write"]
if len(paths) != 1:
    sys.exit(__doc__)
path = paths[0]
text = open(path, encoding="utf-8").read()
block = re.search(r"export const zhCN = \{\n(.*?)\n\};", text, re.S)
if not block:
    sys.exit("zh-hant: no `export const zhCN = { … };` block")
convert = opencc.OpenCC("s2t").convert
lines = ["const zhHantCN: Record<keyof typeof zhCN, string> = {"]
for line in block.group(1).splitlines():
    entry = re.match(r'\s*("[^"]+"):\s*(".*")\s*,?\s*$', line)
    if not entry:
        if line.strip() and not line.strip().startswith("//"):
            sys.exit(f"zh-hant: cannot read this line (one entry per line): {line.strip()}")
        continue
    lines.append(f"  {entry.group(1)}: {json.dumps(convert(json.loads(entry.group(2))), ensure_ascii=False)},")
lines.append("};")
generated = "\n".join(lines)

if not write:
    print(generated)
    sys.exit(0)

existing = re.search(r"const zhHantCN: Record<keyof typeof zhCN, string> = \{\n.*?\n\};", text, re.S)
if existing:
    text = text[: existing.start()] + generated + text[existing.end() :]
else:
    if re.search(r"export const locales\b", text):
        sys.exit("zh-hant: the file already exports `locales` without a zhHantCN block; add `\"zh-Hant-CN\": zhHantCN` by hand")
    text = (
        text.rstrip("\n")
        + "\n\ndeclare module \"../i18nCatalog\" {\n  interface ModuleZhHantMessages extends Record<keyof typeof zhCN, string> {}\n}\n"
        + HEADER + "\n" + generated + "\n\n"
        + "export const locales: Record<string, Partial<Record<keyof typeof zhCN, string>>> = { \"zh-Hant-CN\": zhHantCN };\n"
    )
open(path, "w", encoding="utf-8").write(text)
print(f"zh-hant: wrote {len(lines) - 2} entries to {path}")
