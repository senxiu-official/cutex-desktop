# shellcheck shell=bash
# Sourced by scripts/install-portable.sh (Linux). Ubuntu 23.10+ sets
# kernel.apparmor_restrict_unprivileged_userns=1: Electron's Chromium sandbox then needs either a
# root-owned mode-4755 chrome-sandbox (lost on every in-app update, which builds a new
# releases/<hash>/) or an AppArmor profile that allows user namespaces for the app binary. This
# writes such a profile for every release under <base> (glob releases/*/cutex) and prints the two
# sudo commands that install and load it; it never runs sudo itself.
#
# Test-only overrides (scripts/test-linux-apparmor.sh): CUTEX_TEST_APPARMOR_SYSCTL,
# CUTEX_TEST_APPARMOR_ETC, CUTEX_TEST_APPARMOR_POLICY.

# apparmor_profile_text <name> <attach-path>: the profile, standard Ubuntu "unconfined + userns" shape.
apparmor_profile_text() {
  cat <<PROFILE
# Generated by cutex-desktop scripts/install-portable.sh. Lets Electron's Chromium sandbox use
# unprivileged user namespaces (kernel.apparmor_restrict_unprivileged_userns=1) for every release
# of this install; otherwise unconfined, like Ubuntu's own profiles for chrome / code.

abi <abi/4.0>,
include <tunables/global>

profile $1 "$2" flags=(unconfined) {
  userns,

  # Site-specific additions and overrides. See local/README for details.
  include if exists <local/$1>
}
PROFILE
}

# apparmor_userns_check <base> <out-file>
# Returns 0 when nothing is needed (restriction off, not Linux AppArmor, or a matching profile is
# present and loaded) and 1 when the app will not start until the printed commands run. Messages
# go to stdout.
apparmor_userns_check() {
  local base="$1" out="$2"
  local sysctl="${CUTEX_TEST_APPARMOR_SYSCTL:-/proc/sys/kernel/apparmor_restrict_unprivileged_userns}"
  local etc="${CUTEX_TEST_APPARMOR_ETC:-/etc/apparmor.d}"
  local policy="${CUTEX_TEST_APPARMOR_POLICY:-/sys/kernel/security/apparmor/policy/profiles}"
  [ -r "$sysctl" ] || return 0
  [ "$(tr -d '[:space:]' < "$sysctl")" = "1" ] || return 0

  # AppArmor matches the resolved executable path: resolve symlinks in <base>.
  local rbase attach
  rbase="$(realpath -m -- "$base")"
  attach="$rbase/releases/*/cutex"

  # A profile file in /etc/apparmor.d already naming this attachment?
  local file="" name=""
  if [ -d "$etc" ]; then
    # The attachment as a whole word: "<path>" or a space-delimited <path>.
    file="$(grep -F -l -s -e " $attach " -e "\"$attach\"" -- "$etc"/* 2>/dev/null | head -n1 || true)"
  fi
  if [ -n "$file" ]; then
    name="$(sed -n -E 's/^[[:space:]]*profile[[:space:]]+([^[:space:]"]+)[[:space:]].*/\1/p' "$file" | head -n1)"
    # Loaded profiles are listed (readable without root) as <policy>/<name>.<n>.
    if [ -n "$name" ] && compgen -G "$policy/$name.*" > /dev/null; then
      echo "AppArmor: profile $name ($file) allows user namespaces for $attach"
      return 0
    fi
    if [ ! -d "$policy" ]; then
      echo "AppArmor: $file names $attach (cannot tell whether it is loaded)"
      return 0
    fi
    cat <<MSG

NOTE: AppArmor profile $file for $attach is not loaded.
The app will not start (Chromium sandbox: "SUID sandbox helper binary was found, but is not
configured correctly") until you load it:

  sudo apparmor_parser -r $(printf %q "$file")

MSG
    return 1
  fi

  case "$rbase" in
    *[\"\*\?\[\]\{\}\^,@]*)
      cat <<MSG

NOTE: kernel.apparmor_restrict_unprivileged_userns=1 and $rbase contains characters an AppArmor
path cannot take unescaped (" * ? [ ] { } ^ , @), so no profile was generated. Install to a plainer
--base, or write /etc/apparmor.d/cutex-desktop by hand (see docs/install/AGENT-INSTALL.md).
MSG
      return 1 ;;
  esac

  # One profile per install base; keep the plain name unless another install already uses it.
  name="cutex-desktop"
  if [ -e "$etc/$name" ]; then
    name="cutex-desktop-$(printf '%s' "$rbase" | sha256sum | cut -c1-8)"
  fi
  apparmor_profile_text "$name" "$attach" > "$out"
  cat <<MSG

NOTE: this system restricts unprivileged user namespaces (kernel.apparmor_restrict_unprivileged_userns=1).
The app will not start (Chromium sandbox: "SUID sandbox helper binary was found, but is not
configured correctly") until an AppArmor profile allows them for $attach.
The profile is written to $out; install and load it once (it covers future in-app updates too):

  sudo install -m 644 $(printf %q "$out") $(printf %q "$etc/$name")
  sudo apparmor_parser -r $(printf %q "$etc/$name")

MSG
  return 1
}
